// CI guard: a tenant's Render ADDRESSES follow its row's slug; its IDENTITY does not move.
//
// deploy.ts names the services after the Factory row's slug (<slug>-site, <slug>-<suffix>-api). The
// generator built every address from slugify(company name) instead, and the two differ for real tenants:
// an intake signup is '<name>-intake', a long name is cut at 40 by the generator and not at signup, and
// the store test tenant is 'storetest-…'. So the store's seeded storefront address — which its abandoned-
// cart and review-request emails link to — named a service that does not exist, and a website's canonical
// URLs and sitemap pointed at the wrong host.
//
// The fix is deliberately narrow, and this proves it is: the same slug is ALSO the tenant's identity in its
// own code (the company row the seed looks up, the offline database name, cache names, the booking widget,
// the visualizer). Moving those for an existing tenant would orphan its data. So the real generator runs
// twice for one tenant — without tenant_slug and with one that differs from its name — and every file is
// compared line by line:
//
//   · every line that differs must be an onrender.com address that moved from the name to the row's slug;
//   · nothing else may differ (bcrypt salts and build ids aside — they are random per run);
//   · the row's slug must reach the storefront address, the website's canonical URL and the CRM API host;
//   · and must appear on no line that is not an address.
//
//   bun scripts/check-render-hosts-follow-tenant-slug.ts
import { mkdtempSync, readdirSync, readFileSync, statSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'

const ROOT = new URL('../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
process.env.FACTORY_TEMPLATES_DIR ||= join(ROOT, 'templates')
process.env.FACTORY_PACKAGES_DIR ||= join(ROOT, 'packages')
const OUT = mkdtempSync(join(tmpdir(), 'hosts-'))
process.env.FACTORY_OUTPUT_DIR = OUT
const { generate } = await import(join(ROOT, 'apps/api/src/services/generator.ts'))
const AdmZip = (await import(join(ROOT, 'apps/api/node_modules/adm-zip/adm-zip.js'))).default

let failed = 0
const fail = (m: string) => { failed++; console.error(`FAIL: ${m}`) }

const NAME = 'First Feeder (test)'          // slugify → first-feeder-test
const NAME_SLUG = 'first-feeder-test'
const ROW_SLUG = 'storetest-hosts-check'     // what the Factory row (and so Render) calls it
const config = (tenant_slug?: string) => ({
  id: '00000000-0000-4000-8000-000000000001', tenant_id: '00000000-0000-4000-8000-000000000001', tenant_name: NAME,
  ...(tenant_slug ? { tenant_slug } : {}),
  products: ['crm', 'website'],
  company: { name: NAME, email: 'owner@example.com', city: 'Eau Claire', state: 'WI', zip: '', phone: '', domain: '', domainMode: 'skip', ownerName: 'Ada Owner', industry: 'dropshipping', defaultPassword: 'Fixed-pw-for-the-check-1!' },
  branding: { primaryColor: '#4f46e5', secondaryColor: '#1e3a5f' },
  features: { crm: [], website: [], paid_ads: false },
  integrations: {},
  content: {},
})

const unpack = async (cfg: any, dir: string) => {
  const z = await generate(cfg)
  new AdmZip(z.zipPath).extractAllTo(dir, true)
}
const A = join(OUT, 'name'), B = join(OUT, 'row')
await unpack(config(), A)
await unpack(config(ROW_SLUG), B)

const list = (dir: string, base = dir, out: string[] = []) => {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e)
    if (statSync(p).isDirectory()) list(p, base, out)
    else out.push(p.slice(base.length + 1).replace(/\\/g, '/'))
  }
  return out
}
const filesA = list(A), filesB = new Set(list(B))
if (filesA.length < 200) fail(`only ${filesA.length} files generated — the run is not producing a tenant`)
for (const f of filesA) if (!filesB.has(f)) fail(`${f} exists only without tenant_slug — a path depends on the slug`)

// Random per run, nothing to do with the slug.
const RANDOM = /\$2[aby]\$\d\d\$|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|generateValue|"buildId"|Generated by Twomiah Factory on|\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}Z/
const ADDRESS_MOVE = (a: string, b: string) =>
  a.includes(`${NAME_SLUG}-`) && a.includes('onrender.com') && b.includes(`${ROW_SLUG}-`) && b.includes('onrender.com') &&
  a.split(`${NAME_SLUG}-`).join(`${ROW_SLUG}-`) === b
let moved = 0, compared = 0
const reachedB: string[] = []
for (const f of filesA) {
  if (!filesB.has(f)) continue
  const bufA = readFileSync(join(A, f)), bufB = readFileSync(join(B, f))
  if (bufA.equals(bufB)) { compared++; continue }
  if (/\.(png|jpe?g|webp|gif|ico|zip|woff2?)$/i.test(f)) { fail(`${f}: a binary file changed with the slug`); continue }
  const la = bufA.toString('utf8').split('\n'), lb = bufB.toString('utf8').split('\n')
  if (la.length !== lb.length) { fail(`${f}: ${la.length} lines without tenant_slug, ${lb.length} with — more than an address changed`); continue }
  compared++
  for (let i = 0; i < la.length; i++) {
    if (la[i] === lb[i]) continue
    if (RANDOM.test(la[i]) && RANDOM.test(lb[i])) continue
    if (ADDRESS_MOVE(la[i], lb[i])) { moved++; reachedB.push(`${f}: ${lb[i].trim()}`); continue }
    fail(`${f}:${i + 1} changed and is not an onrender.com address moving to the row's slug\n      without: ${la[i].trim().slice(0, 140)}\n      with:    ${lb[i].trim().slice(0, 140)}`)
  }
}
// The row's slug must be ONLY ever an address in the build that carries it.
for (const f of filesB) {
  if (/\.(png|jpe?g|webp|gif|ico|zip|woff2?)$/i.test(f)) continue
  const lines = readFileSync(join(B, f), 'utf8').split('\n')
  lines.forEach((l, i) => { if (l.includes(ROW_SLUG) && !l.includes(`${ROW_SLUG}-`) ) fail(`${f}:${i + 1} carries the row's slug as an identity, not an address: ${l.trim().slice(0, 140)}`) })
  lines.forEach((l, i) => { if (l.includes(ROW_SLUG) && !/onrender\.com/.test(l)) fail(`${f}:${i + 1} carries the row's slug off an onrender.com address: ${l.trim().slice(0, 140)}`) })
}
const must = [
  ['the store\'s seeded storefront address', /crm-store\/backend\/db\/seed\.ts: .*storefrontOrigin: 'https:\/\/storetest-hosts-check-site\.onrender\.com'/],
  ['the back office\'s STOREFRONT_ORIGIN', /crm-store\/render\.yaml: .*https:\/\/storetest-hosts-check-site\.onrender\.com/],
  ['the CRM API host', /storetest-hosts-check-shop-api\.onrender\.com/],
  ['the website\'s own address', /^website\/.*storetest-hosts-check-site\.onrender\.com/],
] as const
for (const [what, re] of must) if (!reachedB.some((l) => re.test(l))) fail(`${what} did not move to the row's slug`)
// …and the identity stayed put: the company slug the CRM's code knows itself by.
const identity = list(B).filter((f) => /\.(ts|tsx|js|json|ejs)$/.test(f)).some((f) => readFileSync(join(B, f), 'utf8').includes(`'${NAME_SLUG}-cart'`) || readFileSync(join(B, f), 'utf8').includes(`"${NAME_SLUG}"`) || readFileSync(join(B, f), 'utf8').includes(`'${NAME_SLUG}'`))
if (!identity) fail(`the tenant's identity slug '${NAME_SLUG}' is gone from the build with tenant_slug — identity must not move`)

if (process.env.SHOW) for (const l of reachedB) console.log("  " + l.slice(0, 150))
try { rmSync(OUT, { recursive: true, force: true }) } catch {}
if (failed) { console.error(`\nrender hosts: ${failed} problem(s)`); process.exit(1) }
console.log(`render hosts: ${compared} files compared, ${moved} address lines moved to the row's slug, nothing else changed; identity slug unchanged`)
